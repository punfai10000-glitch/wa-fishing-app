"""Step 1 of verifying a hand-picked spot: automatic desk checks for every record in data/locations.json.
It does NOT verify a spot — it lists what's already consistent with official/open data and what a person must
still confirm on site. Writes docs/location-checks.md. A spot may change from 'demo' to 'active' only when every
automatic check passes AND the on-site checklist (see README 'Curating locations') is signed off.
Usage: python pipeline/check_locations.py
"""
import json, math, os
from datetime import date
from shapely.geometry import shape, Point, LineString

ROOT = os.path.join(os.path.dirname(__file__), '..')
P = lambda *a: os.path.join(ROOT, *a)
locs = json.load(open(P('data/locations.json')))['locations']
coast = json.load(open(P('data/coastline.json')))
osm = json.load(open(P('data/osm-spots.geojson')))['features']
zones = []
for f in ['data/zones/closures.geojson', 'data/zones/south-coast.geojson', 'data/zones/access.geojson', 'data/zones/marine-parks.geojson']:
    try:
        for z in json.load(open(P(f)))['features']:
            if z.get('geometry'):
                zones.append((shape(z['geometry']), z['properties']))
    except FileNotFoundError:
        pass

def metres(a, b):
    k = math.cos(math.radians(a[1])) * 111320
    return math.hypot((a[0] - b[0]) * k, (a[1] - b[1]) * 110540)

lines = [LineString(l) for l in coast['lines'] if len(l) > 1]
from shapely.geometry import Polygon
waters = [Polygon(w['rings'][0], w['rings'][1:]) for w in coast.get('water', []) if w.get('rings') and len(w['rings'][0]) > 3]
SRC = {x['id']: x for x in json.load(open(P('data/sources.json')))['sources']}
def water_dist(pt):
    p = Point(pt)
    near = [w for w in waters if w.distance(p) < 0.05]
    return min((0 if w.contains(p) else metres(pt, w.exterior.interpolate(w.exterior.project(p)).coords[0]) for w in near), default=None)
def shore_dist(pt):
    p = Point(pt)
    near = [l for l in lines if l.distance(p) < 0.05]
    if not near:
        return None
    best = min(near, key=lambda l: l.distance(p))
    q = best.interpolate(best.project(p))
    return metres(pt, (q.x, q.y))

REQUIRED = ['exposure', 'access', 'sources', 'safety_notes', 'terrain']
out = [f'# Starter spot desk checks ({date.today().isoformat()})', '',
       'Generated by `pipeline/check_locations.py`. ✓ = consistent with open data; ✗ = fix before going further; '
       '👣 = must be confirmed on site. A spot becomes `active` only when all ✓ and all 👣 are signed off.', '']
for l in locs:
    pt = l['geometry']['coordinates']
    checks = []
    tol = {'jetty': 400, 'groyne': 150}.get(l['type'], 120)   # jetties run out to sea
    if l['type'] == 'estuary' or l.get('estuary'):
        d = water_dist(pt)
        checks.append(('Pin within %d m of mapped river/estuary water' % tol, d is not None and d <= tol, f'{d:.0f} m' if d is not None else 'no mapped water nearby'))
    else:
        d = shore_dist(pt)
        checks.append(('Pin within %d m of the OSM shoreline' % tol, d is not None and d <= tol, f'{d:.0f} m' if d is not None else 'no shoreline nearby'))
    named = [(metres(pt, f['geometry']['coordinates']), f['properties'].get('name') or f['properties'].get('kind') or '?') for f in osm if f.get('geometry', {}).get('type') == 'Point']
    named.sort()
    nd, nn = named[0] if named else (None, None)
    checks.append(('An OpenStreetMap fishing spot within 500 m', nd is not None and nd <= 500, f'{nn} at {nd:.0f} m' if nd is not None else 'none'))
    hits = [p.get('name') for g, p in zones if g.contains(Point(pt)) and p.get('zone_type') != 'marine_park']
    parks = [p.get('name') for g, p in zones if g.contains(Point(pt)) and p.get('zone_type') == 'marine_park']
    checks.append(('Zones / closures recorded for the pin', True, '; '.join(hits + parks) or 'none'))
    missing = [k for k in REQUIRED if not l.get(k)]
    checks.append(('Required fields filled (' + ', '.join(REQUIRED) + ')', not missing, 'missing: ' + ', '.join(missing) if missing else 'all present'))
    srcs = l.get('sources') or []
    official = [x for x in srcs if SRC.get(x if isinstance(x, str) else x.get('id'), {}).get('url') or (isinstance(x, dict) and x.get('url'))]
    checks.append(('At least one official / open source for the spot itself', bool(official), ', '.join(x if isinstance(x, str) else x.get('id', x.get('url', '?')) for x in srcs) or 'none'))
    out += [f"## {l['name']} (`{l['id']}`) — status `{l['status']}`, last verified {l.get('last_verified') or 'never'}", '',
            '| Check | Result | Detail |', '|---|---|---|']
    out += [f"| {c} | {'✓' if ok else '✗'} | {det} |" for c, ok, det in checks]
    out += ['', '👣 On site / with local knowledge:',
            f"- Exact place people fish from (move the pin if needed); access path, parking and walk ({l.get('access')})",
            f"- Which wind and swell directions hit it (now: onshore {l.get('exposure', {}).get('onshore_dirs')}, sheltered {l.get('exposure', {}).get('sheltered_dirs')})",
            f"- Bottom type ({', '.join(l.get('terrain') or [])}) and any hazards (king waves, slippery rock, rips, boats)",
            '- Signs on site (closures, sanctuary, no-fishing areas)', '']
open(P('docs/location-checks.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out[:40]))
